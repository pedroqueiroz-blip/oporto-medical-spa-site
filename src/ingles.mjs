const faltam = new Set();
export function traducao(lang) {
  if (lang !== 'en') return (x) => x;
  return (x) => {
    if (x in EN) return EN[x];
    if (!faltam.has(x)) { faltam.add(x); console.warn('Sem tradução inglesa: «' + x + '» (src/ingles.mjs)'); }
    return x;
  };
}
